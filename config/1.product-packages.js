// Fallback used only if a package_acquisitions row somehow references a
// package_id not defined above (should never happen if this file and the
// pricing page stay in sync) — degrades to Explorer rather than throwing,
// consistent with this codebase's existing "fail safe, not fail loud"
// pattern (see middleware/capabilities.js's fails-open error handling).
const DEFAULT_PACKAGE_ID = 'explorer';

/**
 * Resolves interview settings for a given package — questionBudget
 * (visible), executiveExtensionBudget (Leadership-only additional
 * allowance), and sessionDurationMinutes — frozen onto a session at
 * creation time (controllers/sessionController.js) and never recomputed
 * afterward. This is the one function anything that needs these values
 * should call, rather than reaching into PRODUCT_PACKAGES[id].entitlements
 * directly.
 */
function resolveInterviewPolicy(packageId) {
  const pkg = PRODUCT_PACKAGES[packageId] || PRODUCT_PACKAGES[DEFAULT_PACKAGE_ID];
  return {
    questionBudget: pkg.entitlements.questionBudget,
    executiveExtensionBudget: pkg.entitlements.executiveExtensionBudget || 0,
    sessionDurationMinutes: pkg.entitlements.sessionDurationMinutes,
  };
}

module.exports = { PRODUCT_PACKAGES, DEFAULT_PACKAGE_ID, resolveInterviewPolicy };
